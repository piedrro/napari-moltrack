import numpy as np
import pandas as pd

from moltrack.funcs.export_utils import (
    export_localisation_data,
    export_picasso_localisation,
)
from moltrack.funcs.import_utils import _import_utils


def test_picasso_public_helpers_preserve_selected_numeric_columns_and_metadata(
    tmp_path,
):
    from molcore.interop import read_picasso

    path = tmp_path / "chosen.hdf5"
    columns = {
        "frame": np.array([0, 2], dtype="u4"),
        "x": np.array([1.0, 2.0]),
        "y": np.array([2.0, 3.0]),
        "uncommon": np.array([5.0, 7.0]),
        "particle": np.array([4, 4]),
    }
    metadata = [
        {
            "Width": 8,
            "Height": 9,
            "Frames": 3,
            "Generated by": "MolTrack",
            "custom": "preserved",
        }
    ]
    export_picasso_localisation(
        {
            "data": pd.DataFrame(columns).to_records(index=False),
            "hdf5_path": path,
            "info_path": path.with_suffix(".yaml"),
            "picasso_info": metadata,
        }
    )
    restored, info = read_picasso(path)
    assert list(restored) == list(columns)
    for name in columns:
        np.testing.assert_array_equal(restored[name], columns[name])
    assert info == metadata
    imported = _import_utils().import_hdf5_locs(path, list(columns))
    assert list(imported) == list(columns)
    np.testing.assert_array_equal(imported.uncommon, [5.0, 7.0])


def test_csv_and_pos_keep_explicit_columns_and_frame_convention(tmp_path):
    from molcore.files import read_table

    path = tmp_path / "chosen.csv"
    data = pd.DataFrame(
        {
            "frame": [0, 1],
            "x": [1.0, 2.0],
            "y": [3.0, 4.0],
            "uncommon": [5.0, 6.0],
            "particle": ["a", "a"],
        }
    )
    export_localisation_data(
        {
            "export_mode": "CSV",
            "export_path": path,
            "data": data.to_records(index=False),
        }
    )
    restored = read_table(path)
    assert list(restored) == list(data)
    assert restored["particle"].tolist() == ["a", "a"]
    imported = _import_utils().import_csv_locs(path, list(data))
    assert list(imported) == list(data)
    path = tmp_path / "chosen.pos.out"
    data = pd.DataFrame(
        {
            "frame": [0, 2],
            "x": [1.0, 2.0],
            "y": [3.0, 4.0],
            "photons": [10.0, 20.0],
            "bg": [1.0, 1.0],
            "sx": [1.0, 1.0],
            "sy": [2.0, 2.0],
        }
    )
    export_localisation_data(
        {
            "export_mode": "POS.OUT",
            "export_path": path,
            "data": data.to_records(index=False),
        }
    )
    imported = _import_utils().import_pos_out_locs(path, list(data))
    assert imported.frame.tolist() == [0, 2]


def test_external_table_ids_are_provenance_and_never_reuse_live_ids():
    from test_session_mutations import make_session, rows

    from moltrack.model_io import import_rows

    s = make_session()
    live = s.replace_localizations("data", "acceptor", rows())
    incoming = rows().assign(id=live)
    import_rows(s, "data", "donor", incoming)
    copied = s.query_localizations("data", "donor")
    assert not set(copied.id) & set(live)
    np.testing.assert_array_equal(copied.source_localization_id, live)
    import_rows(
        s, "data", "donor", incoming.assign(particle="external"), tracks=True
    )
    tracks = s.query_tracks("data", "donor")
    assert not set(tracks.id) & (set(live) | set(copied.id))
    np.testing.assert_array_equal(tracks.source_localization_id, live)


def test_external_track_groups_survive_shared_labels_overlap_and_native_roundtrip(
    tmp_path,
):
    from test_session_mutations import make_session

    from moltrack.model_io import import_rows, load_project, save_project

    s = make_session()
    incoming = pd.DataFrame(
        {
            "frame": [0, 1, 0, 1],
            "x": [1.0, 2.0, 3.0, 4.0],
            "y": [2.0, 3.0, 4.0, 5.0],
            "track_id": ["A", "A", "B", "B"],
            "particle": ["same"] * 4,
        }
    )
    s.replace_localizations(
        "data", "acceptor", incoming.drop(columns=["track_id", "particle"])
    )
    live_ids = set(s.query_localizations("data", "acceptor").id)
    import_rows(s, "data", "donor", incoming, tracks=True)
    tracks = s.query_tracks("data", "donor")
    assert tracks.track_id.nunique() == 2
    assert tracks.particle.tolist() == ["same"] * 4
    assert not set(tracks.id) & live_ids
    assert tracks.groupby("track_id").source_track_id.nunique().tolist() == [
        1,
        1,
    ]
    assert set(tracks.source_track_id) == {"A", "B"}
    path = tmp_path / "groups.moltrack"
    save_project(s, path)
    with load_project(path) as restored:
        actual = restored.query_tracks("data", "donor")
        pd.testing.assert_frame_equal(actual, tracks)


def test_file_identity_provenance_survives_two_export_reimport_cycles(
    tmp_path,
):
    from test_session_mutations import make_session

    from moltrack.model_io import import_rows

    s = make_session()
    original = pd.DataFrame(
        {
            "frame": [0, 1],
            "x": [1.0, 2.0],
            "y": [3.0, 4.0],
            "id": [101, 102],
            "localization_id": [201, 202],
            "source_localization_id": [1, 2],
            "track_id": ["live", "live"],
            "source_track_id": ["original", "original"],
            "particle": ["label", "label"],
        }
    )
    first = tmp_path / "first.csv"
    export_localisation_data(
        {
            "export_mode": "CSV",
            "export_path": first,
            "data": original.to_records(index=False),
        }
    )
    selected = [
        "frame",
        "x",
        "y",
        "id",
        "localization_id",
        "source_localization_id",
        "track_id",
        "source_track_id",
        "particle",
    ]
    imported = _import_utils().import_csv_locs(first, selected)
    import_rows(s, "data", "donor", imported, tracks=True)
    tracks = s.query_tracks("data", "donor")
    assert tracks.source_localization_id.tolist() == [1, 2]
    assert tracks.source_localization_id_2.tolist() == [101, 102]
    assert tracks.source_localization_id_3.tolist() == [201, 202]
    assert tracks.source_track_id.tolist() == ["original"] * 2
    assert tracks.source_track_id_2.tolist() == ["live"] * 2
    before_ids = set(tracks.id)
    second = tmp_path / "second.csv"
    export_localisation_data(
        {
            "export_mode": "CSV",
            "export_path": second,
            "data": tracks.to_records(index=False),
        }
    )
    imported = _import_utils().import_csv_locs(second, selected)
    import_rows(s, "data", "donor", imported, tracks=True)
    actual = s.query_tracks("data", "donor")
    assert not set(actual.id) & before_ids
    for name in (
        "source_localization_id",
        "source_localization_id_2",
        "source_localization_id_3",
        "source_track_id",
        "source_track_id_2",
    ):
        np.testing.assert_array_equal(actual[name], tracks[name])
    np.testing.assert_array_equal(actual.source_localization_id_4, tracks.id)
    np.testing.assert_array_equal(actual.source_track_id_3, tracks.track_id)
